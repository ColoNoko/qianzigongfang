/**
 * 「另存为」的文件名 —— **一段名字怎么洗**这条规则只在这里写一遍。
 *
 * 为什么单独立一个模块：译文栏这一个功能里就有**两处**要给「另存为」起默认名
 * （导出校对记录 / 另存一份译文），将来还会有第三处（新增框要从零建 txt）。
 * 每处各写一遍清洗规则，早晚会出现"一个洗了 `?`、另一个没洗"，
 * 而那种 bug 只在用户的作品名里正好带 `?` 的时候才现形。
 *
 * ⚠️ 规则是**保守**的：只做两件事 —— 换掉 Windows 文件名里不许出现的字符、
 * 把连续空白压成一个。**不**做"像不像文件名"的推断（本仓库在启发式上栽过）。
 */

/**
 * 洗掉文件名里不许出现的字符（`\ / : * ? " < > |`），连续空白压成一个，去首尾空白。
 *
 * 作品名里带 `:` 或 `?` 很常见（`这作品?真的:好看`），那种名字直接丢给
 * `dialog.showSaveDialog` 会被系统拒绝或静默截断。
 */
export function sanitizeFileNamePart(value: string | null | undefined): string {
  return String(value ?? '')
    .replace(/[\\/:*?"<>|]/g, '_')
    .replace(/\s+/g, ' ')
    .trim()
}
